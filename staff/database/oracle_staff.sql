-- SkySense / Gestion Staff. Oracle XE 21c, application schema (not SYS).
-- Execute once in the project's PDB. No DROP, no changes to other modules.
-- Qt's setup skips objects already created, allowing a failed setup to resume.
CREATE TABLE SS_STAFF_META (
    SINGLETON NUMBER(1) PRIMARY KEY CHECK (SINGLETON = 1),
    SCHEMA_VERSION NUMBER(3) NOT NULL CHECK (SCHEMA_VERSION = 1),
    REVISION NUMBER(10) DEFAULT 0 NOT NULL CHECK (REVISION >= 0),
    NEXT_ID NUMBER(10) DEFAULT 13 NOT NULL CHECK (NEXT_ID > 0)
);
CREATE TABLE SS_STAFF_ROLE (
    ROLE_NAME NVARCHAR2(80) PRIMARY KEY,
    HAS_REQUIREMENTS NUMBER(1) DEFAULT 0 NOT NULL CHECK (HAS_REQUIREMENTS IN (0,1))
);
CREATE TABLE SS_STAFF_DEPT (
    DEPT_NAME NVARCHAR2(80) PRIMARY KEY
);
CREATE TABLE SS_STAFF_SKILL (
    SKILL_NAME NVARCHAR2(80) PRIMARY KEY
);
CREATE TABLE SS_STAFF_MEMBER (
    STAFF_ID NVARCHAR2(80) PRIMARY KEY,
    FULL_NAME NVARCHAR2(100) NOT NULL,
    EMAIL NVARCHAR2(254) NOT NULL,
    PHONE NVARCHAR2(40),
    ROLE_NAME NVARCHAR2(80) NOT NULL REFERENCES SS_STAFF_ROLE(ROLE_NAME),
    DEPT_NAME NVARCHAR2(80) NOT NULL REFERENCES SS_STAFF_DEPT(DEPT_NAME),
    STATUS VARCHAR2(8) NOT NULL CHECK (STATUS IN ('Active','Inactive')),
    JOINED_ON DATE,
    LAST_LOGIN TIMESTAMP(0),
    NOTE NVARCHAR2(1000)
);
CREATE UNIQUE INDEX SS_STAFF_EMAIL_UQ ON SS_STAFF_MEMBER(LOWER(EMAIL));
CREATE TABLE SS_STAFF_ACCESS (
    STAFF_ID NVARCHAR2(80) REFERENCES SS_STAFF_MEMBER(STAFF_ID) ON DELETE CASCADE,
    MODULE_CODE VARCHAR2(20) CHECK (MODULE_CODE IN ('Stations','Equipment','Maintenance','Services')),
    IS_ALLOWED NUMBER(1) NOT NULL CHECK (IS_ALLOWED IN (0,1)),
    PRIMARY KEY (STAFF_ID,MODULE_CODE)
);
CREATE TABLE SS_STAFF_REQUIREMENT (
    ROLE_NAME NVARCHAR2(80) REFERENCES SS_STAFF_ROLE(ROLE_NAME),
    SKILL_NAME NVARCHAR2(80) REFERENCES SS_STAFF_SKILL(SKILL_NAME),
    REQUIRED_LEVEL NUMBER(1) NOT NULL CHECK (REQUIRED_LEVEL BETWEEN 1 AND 3),
    PRIMARY KEY (ROLE_NAME,SKILL_NAME)
);
CREATE TABLE SS_STAFF_ASSESSMENT (
    STAFF_ID NVARCHAR2(80) REFERENCES SS_STAFF_MEMBER(STAFF_ID) ON DELETE CASCADE,
    SKILL_NAME NVARCHAR2(80) REFERENCES SS_STAFF_SKILL(SKILL_NAME),
    ASSESSED_LEVEL NUMBER(1) NOT NULL CHECK (ASSESSED_LEVEL BETWEEN 0 AND 3),
    PRIMARY KEY (STAFF_ID,SKILL_NAME)
);
CREATE TABLE SS_STAFF_AUDIT (
    AUDIT_NO NUMBER(10) PRIMARY KEY,
    ACTION_AT_UTC TIMESTAMP(3) NOT NULL,
    OPERATOR_NAME NVARCHAR2(256) NOT NULL,
    STAFF_ID NVARCHAR2(80) NOT NULL,
    MEMBER_NAME NVARCHAR2(100),
    ACTION_NAME NVARCHAR2(100) NOT NULL,
    DETAILS CLOB
);
-- STAFF_ID is deliberately not an FK here: history survives deletion of a member.
INSERT INTO SS_STAFF_META (SINGLETON,SCHEMA_VERSION,REVISION,NEXT_ID) VALUES (1,1,0,13);
COMMIT;
