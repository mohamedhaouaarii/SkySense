-- Run this script once in Oracle SQL Developer as user SKYSENSE on XEPDB1.
-- It creates only the Maintenance objects used by the Qt project.

CREATE SEQUENCE SEQ_MAINTENANCE_INTERVENTION
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE MAINTENANCE_INTERVENTION (
    ID              VARCHAR2(30 CHAR)  NOT NULL,
    EQUIPMENT_ID    VARCHAR2(30 CHAR)  NOT NULL,
    TITLE           VARCHAR2(150 CHAR) NOT NULL,
    TECHNICIAN      VARCHAR2(120 CHAR) NOT NULL,
    PRIORITY        VARCHAR2(10 CHAR)  NOT NULL,
    STATUS          VARCHAR2(20 CHAR)  NOT NULL,
    DESCRIPTION_TEXT VARCHAR2(500 CHAR),
    WORK_REPORT     CLOB,
    PLANNED_START   TIMESTAMP          NOT NULL,
    PLANNED_END     TIMESTAMP          NOT NULL,
    REAL_START      TIMESTAMP,
    REAL_END        TIMESTAMP,
    ACTIONS_MASK    NUMBER(3) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_MAINTENANCE_INTERVENTION PRIMARY KEY (ID),
    CONSTRAINT CK_MAINT_INTERVENTION_TITLE CHECK (LENGTH(TRIM(TITLE)) > 0),
    CONSTRAINT CK_MAINT_INTERVENTION_EQUIP CHECK (LENGTH(TRIM(EQUIPMENT_ID)) > 0),
    CONSTRAINT CK_MAINT_INTERVENTION_TECH CHECK (LENGTH(TRIM(TECHNICIAN)) > 0),
    CONSTRAINT CK_MAINT_INTERVENTION_PRIORITY CHECK (PRIORITY IN ('High', 'Medium', 'Low')),
    CONSTRAINT CK_MAINT_INTERVENTION_STATUS CHECK (STATUS IN ('Planned', 'In Progress', 'Completed')),
    CONSTRAINT CK_MAINT_INTERVENTION_DATES CHECK (PLANNED_END >= PLANNED_START),
    CONSTRAINT CK_MAINT_INTERVENTION_REAL_DATES
        CHECK (REAL_END IS NULL OR (REAL_START IS NOT NULL AND REAL_END >= REAL_START)),
    CONSTRAINT CK_MAINT_INTERVENTION_COMPLETE
        CHECK (STATUS <> 'Completed' OR (REAL_START IS NOT NULL AND REAL_END IS NOT NULL)),
    CONSTRAINT CK_MAINT_INTERVENTION_ACTIONS CHECK (ACTIONS_MASK BETWEEN 0 AND 15)
);
