-- sqlplus "/ as sysdba" @verify_app_queries.sql      (ou connecte en SKYSENSE, sans la ligne ALTER SESSION)
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER SESSION SET CURRENT_SCHEMA = SKYSENSE;
SET PAGESIZE 100 LINESIZE 200 FEEDBACK ON
COLUMN NOM_STATION FORMAT A15
COLUMN RESPONSABLE FORMAT A15
COLUMN TITRE FORMAT A28

PROMPT === Station.afficher (equipements derives GERER -> SUIVRE)
SELECT S.ID_STATION, S.NOM_STATION, S.STATUT, (SELECT COUNT(DISTINCT E.IDENTIFIANT_EQUIPEMENT)
  FROM GERER G JOIN EQUIPEMENT E ON E.ID_PERSONNEL=G.ID_PERSONNEL WHERE G.ID_STATION=S.ID_STATION) AS EQUIPEMENTS
FROM STATION S ORDER BY S.NOM_STATION;

PROMPT === Equipement.afficher (SUIVRE)
SELECT E.IDENTIFIANT_EQUIPEMENT, E.TYPE_EQUIPEMENT, TRIM(P.PRENOM || ' ' || P.NOM) AS RESPONSABLE, E.STATUT, E.ID_PERSONNEL
FROM EQUIPEMENT E LEFT JOIN PERSONNEL P ON P.ID_PERSONNEL=E.ID_PERSONNEL ORDER BY E.IDENTIFIANT_EQUIPEMENT;

PROMPT === Maintenance.afficher (REALISER)
SELECT M.ID_MAINTENANCE, M.CODE, M.TITRE, M.STATUT, P.PRENOM, P.NOM, R.ID_PERSONNEL
FROM MAINTENANCE M LEFT JOIN (SELECT ID_MAINTENANCE, MIN(ID_PERSONNEL) ID_PERSONNEL FROM REALISER GROUP BY ID_MAINTENANCE) R
  ON R.ID_MAINTENANCE=M.ID_MAINTENANCE LEFT JOIN PERSONNEL P ON P.ID_PERSONNEL=R.ID_PERSONNEL ORDER BY M.ID_MAINTENANCE DESC;

PROMPT === Service.afficher (AFFECTER)
SELECT V.ID_SERVICE, V.TITRE, V.TYPE_SERVICE, V.DUREE_ESTIMEE, V.DUREE_REELLE, V.STATUT, A.ID_PERSONNEL, P.PRENOM
FROM SERVICE V LEFT JOIN (SELECT ID_SERVICE, MIN(ID_PERSONNEL) ID_PERSONNEL FROM AFFECTER GROUP BY ID_SERVICE) A
  ON A.ID_SERVICE=V.ID_SERVICE LEFT JOIN PERSONNEL P ON P.ID_PERSONNEL=A.ID_PERSONNEL ORDER BY V.ID_SERVICE DESC;

PROMPT === Personnel.afficher
SELECT ID_PERSONNEL, NOM, PRENOM, FONCTION, STATUT, CIN FROM PERSONNEL ORDER BY ID_PERSONNEL DESC;

PROMPT === Tableau de bord : equipements sans station via GERER
SELECT COUNT(*) AS NON_RATTACHES FROM EQUIPEMENT E WHERE (SELECT COUNT(*) FROM GERER G WHERE G.ID_PERSONNEL=E.ID_PERSONNEL)=0;

