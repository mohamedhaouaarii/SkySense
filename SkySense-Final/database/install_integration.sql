CREATE OR REPLACE TRIGGER PERSONNEL_PROFILE_LOG
BEFORE INSERT OR UPDATE OF NOM, PRENOM, EMAIL, TELEPHONE, CIN, FONCTION, STATUT, DATE_ENTREE,
                           DATE_DEBUT_INDISPONIBILITE, DATE_FIN_INDISPONIBILITE, DROITS_MODULES ON PERSONNEL
FOR EACH ROW
DECLARE
    history JSON_ARRAY_T;
    fields VARCHAR2(1000);
    FUNCTION changed(a NVARCHAR2,b NVARCHAR2) RETURN BOOLEAN IS
    BEGIN
        RETURN (a IS NULL AND b IS NOT NULL) OR (a IS NOT NULL AND b IS NULL) OR a<>b;
    END;
    PROCEDURE field(s VARCHAR2) IS
    BEGIN
        IF fields IS NULL THEN fields:=s; ELSE fields:=fields||', '||s; END IF;
    END;
    PROCEDURE event(action VARCHAR2, details VARCHAR2) IS
        item JSON_OBJECT_T:=JSON_OBJECT_T();
    BEGIN
        IF history IS NULL THEN
            IF :OLD.JOURNAL_ACTIVITE IS NULL THEN history:=JSON_ARRAY_T();
            ELSE history:=JSON_ARRAY_T.parse(:OLD.JOURNAL_ACTIVITE); END IF;
        END IF;
        item.put('at',TO_CHAR(SYS_EXTRACT_UTC(SYSTIMESTAMP),'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"'));
        item.put('actor',COALESCE(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),SYS_CONTEXT('USERENV','SESSION_USER')));
        item.put('action',action);
        item.put('details',details);
        history.append(item);
    END;
BEGIN
    IF INSERTING THEN
        event('Staff created','Staff profile created');
    ELSE
        IF changed(:OLD.NOM,:NEW.NOM) OR changed(:OLD.PRENOM,:NEW.PRENOM) THEN field('Name'); END IF;
        IF changed(:OLD.EMAIL,:NEW.EMAIL) THEN field('Email'); END IF;
        IF changed(:OLD.CIN,:NEW.CIN) THEN field('CIN'); END IF;
        IF changed(:OLD.TELEPHONE,:NEW.TELEPHONE) THEN field('Phone'); END IF;
        IF changed(:OLD.FONCTION,:NEW.FONCTION) THEN field('Function'); END IF;
        IF changed(:OLD.STATUT,:NEW.STATUT) THEN field('Status'); END IF;
        IF changed(TO_CHAR(:OLD.DATE_ENTREE,'YYYY-MM-DD'),TO_CHAR(:NEW.DATE_ENTREE,'YYYY-MM-DD')) THEN field('Join date'); END IF;
        IF fields IS NOT NULL THEN event('Profile updated',fields); END IF;
    END IF;
    IF changed(TO_CHAR(:OLD.DATE_DEBUT_INDISPONIBILITE,'YYYY-MM-DD'),TO_CHAR(:NEW.DATE_DEBUT_INDISPONIBILITE,'YYYY-MM-DD'))
        OR changed(TO_CHAR(:OLD.DATE_FIN_INDISPONIBILITE,'YYYY-MM-DD'),TO_CHAR(:NEW.DATE_FIN_INDISPONIBILITE,'YYYY-MM-DD')) THEN
        event('Leave updated',CASE WHEN :NEW.DATE_DEBUT_INDISPONIBILITE IS NULL THEN 'Leave period cleared'
            ELSE TO_CHAR(:NEW.DATE_DEBUT_INDISPONIBILITE,'YYYY-MM-DD')||' to '||TO_CHAR(:NEW.DATE_FIN_INDISPONIBILITE,'YYYY-MM-DD') END);
    END IF;
    IF NVL(:OLD.DROITS_MODULES,-1)<>NVL(:NEW.DROITS_MODULES,-1) THEN
        fields:=NULL;
        IF BITAND(:NEW.DROITS_MODULES,1)>0 THEN field('Stations'); END IF;
        IF BITAND(:NEW.DROITS_MODULES,2)>0 THEN field('Equipment'); END IF;
        IF BITAND(:NEW.DROITS_MODULES,4)>0 THEN field('Maintenance'); END IF;
        IF BITAND(:NEW.DROITS_MODULES,8)>0 THEN field('Services'); END IF;
        event('Access changed',CASE WHEN fields IS NULL THEN 'No modules granted' ELSE 'Granted: '||fields END);
    END IF;
    IF history IS NOT NULL THEN :NEW.JOURNAL_ACTIVITE:=history.to_clob(); END IF;
END;
/
