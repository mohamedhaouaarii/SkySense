CREATE TABLE PERSONNEL (
 ID_PERSONNEL NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 STAFF_KEY VARCHAR2(80 CHAR) NOT NULL UNIQUE, CIN VARCHAR2(20 CHAR) CONSTRAINT UQ_PERSONNEL_CIN UNIQUE,
 NOM NVARCHAR2(100) NOT NULL, PRENOM NVARCHAR2(100) NOT NULL, EMAIL NVARCHAR2(254) NOT NULL,
 TELEPHONE NVARCHAR2(40), FONCTION NVARCHAR2(80) NOT NULL, STATUT VARCHAR2(8 CHAR) DEFAULT 'Active' NOT NULL,
 DATE_ENTREE DATE,DATE_DEBUT_INDISPONIBILITE DATE,DATE_FIN_INDISPONIBILITE DATE,
 DROITS_MODULES NUMBER(2) CHECK (DROITS_MODULES BETWEEN 0 AND 15), JOURNAL_ACTIVITE CLOB CHECK (JOURNAL_ACTIVITE IS JSON),
 CHECK(STATUT IN ('Active','Inactive')), CHECK((DATE_DEBUT_INDISPONIBILITE IS NULL AND DATE_FIN_INDISPONIBILITE IS NULL) OR (DATE_DEBUT_INDISPONIBILITE IS NOT NULL AND DATE_FIN_INDISPONIBILITE IS NOT NULL AND DATE_DEBUT_INDISPONIBILITE<=DATE_FIN_INDISPONIBILITE))
);
