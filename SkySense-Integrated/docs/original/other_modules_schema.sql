-- Run once in Oracle SQL Developer as SKYSENSE connected to XEPDB1.
-- These are empty catalog tables for the other SkySense modules.
-- They are not connected to the Qt application's CRUD operations.

CREATE TABLE SKYSENSE_STATIONS (
    STATION_ID       VARCHAR2(20 CHAR)  NOT NULL,
    STATION_NAME     VARCHAR2(120 CHAR) NOT NULL,
    STATION_TYPE     VARCHAR2(80 CHAR),
    CITY_REGION      VARCHAR2(200 CHAR),
    EQUIPMENT_COUNT  NUMBER(5) DEFAULT 0 NOT NULL,
    AVAILABILITY_PCT NUMBER(5,2) DEFAULT 0 NOT NULL,
    STATUS           VARCHAR2(30 CHAR),
    LAST_UPDATE      DATE,
    CONSTRAINT PK_SKYSENSE_STATIONS PRIMARY KEY (STATION_ID),
    CONSTRAINT CK_SKYSENSE_STATION_AVAIL CHECK (AVAILABILITY_PCT BETWEEN 0 AND 100)
);

CREATE TABLE SKYSENSE_EQUIPMENT (
    EQUIPMENT_ID   VARCHAR2(30 CHAR)  NOT NULL,
    EQUIPMENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    STATION_NAME   VARCHAR2(120 CHAR),
    UNIT           VARCHAR2(40 CHAR),
    UPDATED_AT     DATE,
    STATUS         VARCHAR2(30 CHAR),
    MODEL          VARCHAR2(120 CHAR),
    SERIAL_NUMBER  VARCHAR2(100 CHAR),
    PHOTO_BASE64   CLOB,
    LOCATION       VARCHAR2(200 CHAR),
    CONSTRAINT PK_SKYSENSE_EQUIPMENT PRIMARY KEY (EQUIPMENT_ID)
);

CREATE TABLE SKYSENSE_STAFF (
    STAFF_ID             VARCHAR2(20 CHAR)  NOT NULL,
    FULL_NAME            VARCHAR2(150 CHAR) NOT NULL,
    EMAIL                VARCHAR2(254 CHAR),
    PROFESSIONAL_ROLE    VARCHAR2(120 CHAR),
    STATUS               VARCHAR2(30 CHAR),
    PHONE                VARCHAR2(40 CHAR),
    JOINED_DATE          DATE,
    UNAVAILABLE_FROM     DATE,
    UNAVAILABLE_TO       DATE,
    CONSTRAINT PK_SKYSENSE_STAFF PRIMARY KEY (STAFF_ID)
);

CREATE TABLE SKYSENSE_SERVICES (
    SERVICE_ID       VARCHAR2(30 CHAR)  NOT NULL,
    TITLE            VARCHAR2(150 CHAR) NOT NULL,
    SERVICE_TYPE     VARCHAR2(50 CHAR),
    STATION_CODE     VARCHAR2(30 CHAR),
    STATION_NAME     VARCHAR2(120 CHAR),
    ASSIGNEE         VARCHAR2(120 CHAR),
    SERVICE_DATE     DATE,
    START_TIME       VARCHAR2(8 CHAR),
    END_TIME         VARCHAR2(8 CHAR),
    PRIORITY         VARCHAR2(10 CHAR),
    STATUS           VARCHAR2(20 CHAR),
    DESCRIPTION_TEXT CLOB,
    CHECKLIST_TEXT   CLOB,
    CHECKLIST_DONE   CLOB,
    ACTUAL_END_TIME  VARCHAR2(8 CHAR),
    STATION_ID       NUMBER(10),
    PERSONNEL_ID     NUMBER(10),
    CONSTRAINT PK_SKYSENSE_SERVICES PRIMARY KEY (SERVICE_ID)
);

