-- Optional one-time copy of Donia's existing Staff data into the group schema.
-- Run as SYS/SYSTEM on XEPDB1. Source DONIA is read only.
-- Existing destination primary keys are kept, never overwritten.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
-- On the first import, replace the seeded requirement flags with the source values.
-- Later imports keep the destination's role configuration.
DECLARE
    member_count PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO member_count FROM SKYSENSE.SS_STAFF_MEMBER;
    IF member_count=0 THEN
        UPDATE SKYSENSE.SS_STAFF_ROLE t
        SET HAS_REQUIREMENTS=(SELECT s.HAS_REQUIREMENTS FROM DONIA.SS_STAFF_ROLE s WHERE s.ROLE_NAME=t.ROLE_NAME)
        WHERE EXISTS (SELECT 1 FROM DONIA.SS_STAFF_ROLE s WHERE s.ROLE_NAME=t.ROLE_NAME);
    END IF;
END;
/
INSERT INTO SKYSENSE.SS_STAFF_ROLE
SELECT s.* FROM DONIA.SS_STAFF_ROLE s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_ROLE t WHERE t.ROLE_NAME=s.ROLE_NAME);
INSERT INTO SKYSENSE.SS_STAFF_DEPT
SELECT s.* FROM DONIA.SS_STAFF_DEPT s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_DEPT t WHERE t.DEPT_NAME=s.DEPT_NAME);
INSERT INTO SKYSENSE.SS_STAFF_SKILL
SELECT s.* FROM DONIA.SS_STAFF_SKILL s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_SKILL t WHERE t.SKILL_NAME=s.SKILL_NAME);
INSERT INTO SKYSENSE.SS_STAFF_MEMBER
SELECT s.* FROM DONIA.SS_STAFF_MEMBER s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_MEMBER t WHERE t.STAFF_ID=s.STAFF_ID);
INSERT INTO SKYSENSE.SS_STAFF_ACCESS
SELECT s.* FROM DONIA.SS_STAFF_ACCESS s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_ACCESS t WHERE t.STAFF_ID=s.STAFF_ID AND t.MODULE_CODE=s.MODULE_CODE);
INSERT INTO SKYSENSE.SS_STAFF_REQUIREMENT
SELECT s.* FROM DONIA.SS_STAFF_REQUIREMENT s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_REQUIREMENT t WHERE t.ROLE_NAME=s.ROLE_NAME AND t.SKILL_NAME=s.SKILL_NAME);
INSERT INTO SKYSENSE.SS_STAFF_ASSESSMENT
SELECT s.* FROM DONIA.SS_STAFF_ASSESSMENT s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_ASSESSMENT t WHERE t.STAFF_ID=s.STAFF_ID AND t.SKILL_NAME=s.SKILL_NAME);
INSERT INTO SKYSENSE.SS_STAFF_AUDIT
SELECT s.* FROM DONIA.SS_STAFF_AUDIT s WHERE NOT EXISTS (SELECT 1 FROM SKYSENSE.SS_STAFF_AUDIT t WHERE t.AUDIT_NO=s.AUDIT_NO);
UPDATE SKYSENSE.SS_STAFF_META
SET NEXT_ID = GREATEST(NEXT_ID, (SELECT NEXT_ID FROM DONIA.SS_STAFF_META WHERE SINGLETON=1))
WHERE SINGLETON=1;
COMMIT;
