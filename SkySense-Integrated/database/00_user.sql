-- Run in SQL*Plus as SYSDBA on Oracle XE 21c.
-- The DBA role below is the explicit account setup requested by the group.
SET ECHO OFF
SET VERIFY OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER SESSION SET CONTAINER = XEPDB1;
ACCEPT GROUP_PASSWORD CHAR PROMPT 'Mot de passe du compte SKYSENSE : ' HIDE
DECLARE
    n PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME='SKYSENSE';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE USER SKYSENSE IDENTIFIED BY "&GROUP_PASSWORD" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP';
    END IF;
END;
/
UNDEFINE GROUP_PASSWORD
GRANT CONNECT, RESOURCE, DBA TO SKYSENSE;
