-- SkySense - Gestion des equipements
-- Execute this script after the common STATION table has been created.

CREATE TABLE EQUIPEMENT (
    ID_EQUIPEMENT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TYPE_EQUIPEMENT VARCHAR2(50) NOT NULL,
    MODELE VARCHAR2(100) NOT NULL,
    NUMERO_SERIE VARCHAR2(80) NOT NULL,
    UNITE_MESURE VARCHAR2(20),
    STATUT VARCHAR2(20) NOT NULL,
    DATE_MISE_A_JOUR DATE NOT NULL,
    PHOTO BLOB,
    ID_STATION NUMBER NOT NULL,
    CONSTRAINT UQ_EQUIPEMENT_NUMERO_SERIE UNIQUE (NUMERO_SERIE),
    CONSTRAINT CK_EQUIPEMENT_STATUT CHECK (STATUT IN ('Online', 'Offline', 'Maintenance')),
    CONSTRAINT FK_EQUIPEMENT_STATION
        FOREIGN KEY (ID_STATION)
        REFERENCES STATION(ID_STATION)
);

CREATE INDEX IDX_EQUIPEMENT_STATION ON EQUIPEMENT(ID_STATION);
CREATE INDEX IDX_EQUIPEMENT_STATUT ON EQUIPEMENT(STATUT);
