SET SERVEROUTPUT ON
SET LINESIZE 200
SET FEEDBACK ON

PROMPT == 1. Liste du personnel (loadPersonnel)
SELECT ID_PERSONNEL, PRENOM, NOM, STATUT FROM PERSONNEL ORDER BY NOM, PRENOM;

PROMPT == 2. Chargement des services (loadAll)
SELECT ID_SERVICE, TITRE, TYPE_SERVICE, DESCRIPTION,
       TO_CHAR(DATE_PREVUE, 'YYYY-MM-DD HH24:MI'), DUREE_ESTIMEE, DUREE_REELLE,
       PRIORITE, STATUT, NVL(PRIX, 0)
FROM SERVICE ORDER BY ID_SERVICE;

PROMPT == 3. Chargement des affectations (loadAll)
SELECT A.ID_SERVICE, P.ID_PERSONNEL, P.PRENOM, P.NOM
FROM AFFECTER A JOIN PERSONNEL P ON P.ID_PERSONNEL = A.ID_PERSONNEL
ORDER BY A.ID_SERVICE, P.NOM, P.PRENOM;

PROMPT == 4. Ajout (insert) : MAX+1 puis INSERT SERVICE + AFFECTER
LOCK TABLE SERVICE IN EXCLUSIVE MODE;
SELECT NVL(MAX(ID_SERVICE), 0) + 1 AS PROCHAIN_ID FROM SERVICE;
INSERT INTO SERVICE (ID_SERVICE, TITRE, TYPE_SERVICE, DESCRIPTION, DATE_PREVUE,
                     DUREE_ESTIMEE, DUREE_REELLE, PRIORITE, STATUT, PRIX)
VALUES ((SELECT NVL(MAX(ID_SERVICE), 0) + 1 FROM SERVICE), 'TEST Service verification', 'Maintenance',
        'Ligne de test', TO_TIMESTAMP('2026-11-10 09:00', 'YYYY-MM-DD HH24:MI'), 120, NULL, 'Medium', 'Scheduled', 99.50);
INSERT INTO AFFECTER (ID_PERSONNEL, ID_SERVICE)
VALUES (1, (SELECT ID_SERVICE FROM SERVICE WHERE TITRE = 'TEST Service verification'));
INSERT INTO AFFECTER (ID_PERSONNEL, ID_SERVICE)
VALUES (2, (SELECT ID_SERVICE FROM SERVICE WHERE TITRE = 'TEST Service verification'));

PROMPT == 5. Modification (update) : UPDATE SERVICE + remplacement des affectations
UPDATE SERVICE SET TYPE_SERVICE = 'Repair', DESCRIPTION = 'Test modifie',
       DATE_PREVUE = TO_TIMESTAMP('2026-11-11 10:30', 'YYYY-MM-DD HH24:MI'),
       DUREE_ESTIMEE = 90, DUREE_REELLE = 80, PRIORITE = 'High', STATUT = 'Completed', PRIX = 120.00
WHERE ID_SERVICE = (SELECT ID_SERVICE FROM SERVICE WHERE TITRE = 'TEST Service verification');
DELETE FROM AFFECTER WHERE ID_SERVICE = (SELECT ID_SERVICE FROM SERVICE WHERE TITRE = 'TEST Service verification');
INSERT INTO AFFECTER (ID_PERSONNEL, ID_SERVICE)
VALUES (3, (SELECT ID_SERVICE FROM SERVICE WHERE TITRE = 'TEST Service verification'));
SELECT S.ID_SERVICE, S.TITRE, TO_CHAR(S.DATE_PREVUE, 'YYYY-MM-DD HH24:MI') AS DATE_PREVUE,
       S.DUREE_ESTIMEE, S.DUREE_REELLE, S.STATUT, S.PRIX, A.ID_PERSONNEL
FROM SERVICE S JOIN AFFECTER A ON A.ID_SERVICE = S.ID_SERVICE
WHERE S.TITRE = 'TEST Service verification';

PROMPT == 6. Titre unique (UQ_SERVICE_TITRE) : l'erreur ORA-00001 ci-dessous est ATTENDUE
INSERT INTO SERVICE (ID_SERVICE, TITRE, DATE_PREVUE, DUREE_ESTIMEE, PRIORITE, STATUT)
VALUES ((SELECT NVL(MAX(ID_SERVICE), 0) + 1 FROM SERVICE), 'TEST Service verification',
        TO_TIMESTAMP('2026-11-12 09:00', 'YYYY-MM-DD HH24:MI'), 60, 'Low', 'Scheduled');

PROMPT == 7. Suppression (remove) : AFFECTER puis SERVICE
DELETE FROM AFFECTER WHERE ID_SERVICE = (SELECT ID_SERVICE FROM SERVICE WHERE TITRE = 'TEST Service verification');
DELETE FROM SERVICE WHERE TITRE = 'TEST Service verification';

ROLLBACK;
